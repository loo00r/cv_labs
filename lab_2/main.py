# Отримання ширини та висоти з кортежу зображення
(h, w) = img.shape[:2]
# Обчислення центру зображення
center = (int(w / 2), int(h / 2))
# Створення матриці обертання
r_matrix = cv2.getRotationMatrix2D(center, -60, 0.4)
# Виконання афінного перетворення
rotated = cv2.warpAffine(img, r_matrix, (w, h))

# Відображення картинки
cv2.imshow('Rotated photo', rotated)

